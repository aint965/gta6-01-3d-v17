// Seeded RNG (mulberry32) + small helpers. Pure, no DOM, importable from Node.
export function createRandom(seed) {
  let a = seed >>> 0;
  return function next() {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function pick(rng, arr) {
  return arr[Math.floor(rng() * arr.length)];
}

export function range(rng, lo, hi) {
  return lo + rng() * (hi - lo);
}

export function rangeInt(rng, lo, hi) {
  return lo + Math.floor(rng() * (hi - lo + 1));
}

// Parse "#rrggbb" into [r,g,b] 0..1 floats.
export function hexRgb(hex) {
  const n = parseInt(hex.slice(1), 16);
  return [((n >> 16) & 255) / 255, ((n >> 8) & 255) / 255, (n & 255) / 255];
}

// Slight per-instance shade variation so repeated colours do not look cloned.
export function shade(rgb, rng, amount) {
  const f = 1 - amount / 2 + rng() * amount;
  return [rgb[0] * f, rgb[1] * f, rgb[2] * f];
}
